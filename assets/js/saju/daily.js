function hash(str) { let h = 2166136261; for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 16777619); } return h >>> 0; }
const dayNo = (d) => Math.floor(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) / 864e5);

/**
 * god: 오늘 들어오는 십신 · todayStem/todayBranch: 오늘 일진 · mine: { stemIdx, branchIdx } 내 일주
 * 같은 사람이라도 날마다, 같은 날이라도 사람마다 다른 문장을 골라요.
 */
export function dailyText(god, todayStem, todayBranch, mine, date = new Date()) {
  const P = T[god] || T.비견;
  const me = mine || { stemIdx: 0, branchIdx: 0 };
  const base = dayNo(date) + me.stemIdx * 7 + me.branchIdx * 3;
  const pick = (k) => { const arr = P[k]; return arr[(base + hash(k)) % arr.length]; };
  const keyword = `${STEM_H[todayStem]}${BR_H[todayBranch]}(${STEM_KR[todayStem]}${BR_KR[todayBranch]}) · ${BR_IMG[todayBranch]} 위의 ${STEM_IMG[todayStem]} — 키워드 ‘${STEM_WORD[todayStem]}’과 ‘${BR_WORD[todayBranch]}’`;
  const a = me.branchIdx, b = todayBranch;
  let rel = "";
  if (LIUHE.some(([x, y]) => (x === a && y === b) || (x === b && y === a))) rel = REL_LINE.hap(a, b);
  else if (Math.abs(a - b) === 6) rel = REL_LINE.chung(a, b);
  else if (a === b) rel = REL_LINE.same(a);
  else if (SAMHAP.some((g) => g.includes(a) && g.includes(b))) rel = REL_LINE.samhap(a, b);
  return { theme: pick("theme"), love: pick("love"), work: pick("work"), money: pick("money"), advice: pick("advice"), line: pick("line"), keyword, rel };
}
